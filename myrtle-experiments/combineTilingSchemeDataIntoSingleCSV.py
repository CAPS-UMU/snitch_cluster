def checkForTimeout(r):
    output = f"{os.path.dirname(os.path.dirname(r))}/output.txt"
    timeoutMsg="what():  Myrtle Experiment Timeout"
    if os.path.exists(output):
        with open(output, 'r', encoding='utf-8') as file:
            str = file.read()
            return timeoutMsg in str
    else:
        return False


def main():
    if len(sys.argv) !=3:
        print("\t",end='')
        print("USAGE: Requires search space CSV file name and kernel directory as input.")
    else:
        f=sys.argv[1]
        print("\t\t",end='')
        print(f)
        df = pd.read_csv(f)
        logsRootPath=f"{sys.argv[2]}"
        # generate file path to each tiling scheme's csv file (generated by extractKernelTimeFromJsons.py)
        # collect the csv file paths into a list of paths
        all_files = df.apply(lambda x : f'{logsRootPath}/{x["FakeNN JSON Name"]}/build/logs/{x["FakeNN JSON Name"]}.csv', axis=1).to_list()
        # take the first csv file in the list, and merge the rest of the csv files into that first one
        original = all_files[0]
        rest = all_files[1:]
        orig = pd.read_csv(original,index_col=False)
        cols = list(orig.columns)
        for r in rest:
            if not os.path.exists(r):
                if checkForTimeout(r):
                    name = os.path.basename(os.path.dirname(os.path.dirname(os.path.dirname(r))))
                    print("\t\t",end='')
                    print(f"{name}: Detected Timeout")
                    my_row = dict(zip(cols, [-1] * len(cols)))
                    my_row["FakeNN JSON Name"] = name
                    timeoutdf=pd.DataFrame([my_row],columns=my_row.keys())
                    orig=pd.concat([orig,timeoutdf])
                else:
                    print("\t\t",end='')
                    print(f"Skipping {r}")
            else:
                rdf = pd.read_csv(r,index_col=False)
                rdf = rdf[cols]
                orig=pd.concat([orig,rdf])
        # file name for combined data is the original csv name with "results" appended to the end
        outputFile = f'{f[:-4]}-results.csv'
        df = df[["FakeNN JSON Name"]] # only take the unique id from the search space
        df = df.merge(orig, how='outer')
        print("\t\t",end='')
        print(outputFile)
        df.to_csv(outputFile,index=False)
        # if there are rows without timing information, emit a second file with only the timed rows
        if df["dma"].isnull().any() :
            print("\t\t",end='')
            print("Attention: some of the rows do not contain timing information")
            unskipped = df[df["dma"].notnull()] # df[df['col'].notnull()] ]
            outputFile = f'{f[:-4]}-results-unskipped.csv'
            unskipped.to_csv(outputFile,index=False)
            print("\t\t",end='')
            print(outputFile)
            skipped = df[df["dma"].isnull()]
            outputFile = f'{f[:-4]}-results-skipper.csv'
            skipped.to_csv(outputFile,index=False)
            print("\t\t",end='')
            print(outputFile)
       

if __name__ == "__main__":
    main()

   
    